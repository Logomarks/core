// Type-level usage check (`npm run typecheck`); never executed.
import { U, D, circle, rect, svg, robust, seeded, over, skelSolid, knockout, glitchMark, iso, isoBlock, isoPile, OPS, type Shape, type Point } from '../src/geometry/index.js';
import { parsePath, shapes, svgShape, bounds, pathRings, nonzeroFill, windingFill, ringsMeet, type FilledPath, type Segment } from '../src/svg/index.js';
import { fitMark, checkFit, type Fitted } from '../src/fit/index.js';
import { markParts, smallParts, shapeTags, widths, type ShapeTag } from '../src/analyse/index.js';
import { outlineSignature, variants, iou, nearestAll } from '../src/similar/index.js';
import { adjustPaths, NO_ADJUST, reshape, pixelGrid, pixelPath, type Adjust } from '../src/edit/index.js';
import { exact, badge, tiles, letterSolid, runIndustry, type IndustryMark } from '../src/parts/index.js';
import { frameOf, fill, components } from '../src/raster/index.js';
import { bundleKit } from '../src/skill/bundle.js';

robust();
Math.random = seeded('Moonrise');
const s: Shape = U(D(rect(0, 0, 300, 300), circle(150, 0, 120)), circle(150, 30, 46));
const p: Point = [1, 2];
const file: string = svg(over(s, skelSolid('A', 300, 60)));
const badged: Shape = knockout('disc', letterSolid('K', 260, 64));
const glitched: Shape = glitchMark(file, { kind: 'shear', cuts: [256] });
const P = iso(40);
const stack: Shape = isoPile([isoBlock(P, [[0, 0], [2, 0], [2, 2], [0, 2]], { z1: 1 })]);
const segs: Segment[] = parsePath('M0 0H10V10Z');
const paths: FilledPath[] = shapes(file);
const fitted: Fitted = fitMark(file);
const problems: string[] = checkFit(fitted.svg).problems;
const read = markParts(paths, { seed: 'moonrise' });
const tags: ShapeTag[] = shapeTags(new Float32Array(128 * 128), { w: 448, h: 448 });
const sig = outlineSignature(new Float32Array(48 * 48));
const best: number = Math.max(...variants(sig).map((v) => iou(v, sig)));
const near: Record<string, string[]> = nearestAll([{ slug: 'a', alpha: sig }]);
const a: Adjust = { ...NO_ADJUST, turns: 1 };
const out: string = adjustPaths('<path d="M0 0H10V10Z"/>', a, { canCut: () => true });
const bold: string | null = reshape('<path d="M0 0H10V10Z"/>', 2, 0);
const d: string | null = pixelPath([1], pixelGrid(0.5, { x: 0, y: 0, width: 10, height: 10 }));
const exactShape: Shape = exact((g) => U(rect(0, 0, 100, 100), rect(100 + g, 0, 100, 100)));
const plate: Shape = badge('squircle', (g) => tiles(['S .', '. S'], { g }));
const M: Record<string, IndustryMark> = { Plate: { trade: 'Test', style: 'Bold', fn: () => plate } };
if (process.argv[9]) runIndustry(999, M);
const bm = fill([{ rings: [[[0, 0], [10, 0], [10, 10]]], evenodd: false }], frameOf([{ rings: [[[0, 0], [10, 0], [10, 10]]], evenodd: false }], 2));
console.log(p, badged, glitched, stack, segs, problems, read, smallParts(read.parts), tags, best, near, out, bold, d, exactShape, components(bm), widths(paths), svgShape(file), bounds(paths), bundleKit().length);
const glyphRings = pathRings('M0 0H100V100H0ZM-50 40H150V60H-50Z');
const glyph: Shape = ringsMeet(glyphRings) ? windingFill(glyphRings, OPS) : nonzeroFill(glyphRings, OPS);
console.log(glyph);
